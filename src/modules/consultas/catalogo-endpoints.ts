/** Normaliza um texto para a busca: minúsculas e sem acentos. */
function normalizar(texto: string): string {
  return texto
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

/**
 * Procura endpoints do catálogo por texto livre.
 *
 * A busca é tolerante a acentos e caixa e varre título, descrição, domínio, caminho,
 * tags e nomes de parâmetros. Vários termos funcionam como filtro aditivo (todos devem
 * casar). Passe `dominio` para restringir a um domínio específico.
 *
 * @param termo Texto a procurar; vazio devolve o catálogo inteiro (respeitando `dominio`).
 * @param dominio Domínio opcional para restringir a busca.
 * @returns Lista de {@link EndpointInfo} que casam com o termo, na ordem do catálogo.
 * @example
 * const resultados = buscarEndpoints('cartao');
 * const deSancoes = buscarEndpoints('', 'sancoes');
 */
export function buscarEndpoints(termo = '', dominio?: DominioEndpoint): EndpointInfo[] {
  const porDominio = dominio
    ? catalogoEndpoints.filter((e) => e.dominio === dominio)
    : catalogoEndpoints;
  const termos = normalizar(termo).split(/\s+/).filter(Boolean);
  if (termos.length === 0) return [...porDominio];
  return porDominio.filter((endpoint) => {
    const alvo = normalizar(
      [
        endpoint.recurso,
        endpoint.caminho,
        endpoint.dominio,
        endpoint.titulo,
        endpoint.descricao,
        ...endpoint.tags,
        ...endpoint.parametros.map((p) => p.nome),
      ].join(' '),
    );
    return termos.every((t) => alvo.includes(t));
  });
}
