/**
 * Metadados de um endpoint oficial, voltados à descoberta e à documentação.
 *
 * Cada entrada descreve o recurso em linguagem natural (`titulo`, `descricao`), os
 * parâmetros aceitos e exemplos, permitindo que consumidores encontrem rapidamente o
 * endpoint certo sem consultar o Swagger oficial.
 */
export interface EndpointInfo {
  /** Chave do endpoint em {@link endpoints}, usada em `api.consultas.consultar`. */
  recurso: EndpointConsulta;
  /** Caminho literal da requisição, com placeholders entre chaves quando houver. */
  caminho: string;
  /** Domínio de negócio do endpoint. */
  dominio: DominioEndpoint;
  /** Título curto e legível em português. */
  titulo: string;
  /** Explicação do que o endpoint retorna e quando usá-lo. */
  descricao: string;
  /** Parâmetros de query/rota aceitos, com a indicação de obrigatoriedade. */
  parametros: EndpointParametro[];
  /** `true` quando a resposta é paginada (aceita `pagina`). */
  paginado: boolean;
  /** `true` quando o endpoint devolve um único registro em vez de uma lista. */
  registroUnico: boolean;
  /** Palavras-chave extras que ajudam a busca textual. */
  tags: string[];
}

/** Descrição de um parâmetro aceito por um endpoint. */
export interface EndpointParametro {
  /** Nome do parâmetro, como enviado na query ou no caminho. */
  nome: string;
  /** `true` quando o parâmetro é obrigatório. */
  obrigatorio: boolean;
  /** Explicação curta do parâmetro. */
  descricao: string;
}

/** Helper interno: monta um parâmetro de query obrigatório. */
const req = (nome: string, descricao: string): EndpointParametro => ({
  nome,
  obrigatorio: true,
  descricao,
});
/** Helper interno: monta um parâmetro de query opcional. */
const opt = (nome: string, descricao: string): EndpointParametro => ({
  nome,
  obrigatorio: false,
  descricao,
});
/** Parâmetro `pagina`, presente em todo endpoint paginado. */
const pagina = opt('pagina', 'Página a consultar (padrão 1).');

